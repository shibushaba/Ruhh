const kRuhhEmojiQuickCount = 10;

List<String> ruhhEmojiQuickPicks({String? selected}) {
  final quick = kRuhhEmojiCatalog.take(kRuhhEmojiQuickCount).toList();
  if (selected != null &&
      selected.isNotEmpty &&
      !quick.contains(selected) &&
      kRuhhEmojiCatalog.contains(selected)) {
    return [selected, ...quick.take(kRuhhEmojiQuickCount - 1)];
  }
  if (selected != null &&
      selected.isNotEmpty &&
      !quick.contains(selected) &&
      !kRuhhEmojiCatalog.contains(selected)) {
    return [selected, ...quick.take(kRuhhEmojiQuickCount - 1)];
  }
  return quick;
}
